// crawlerAliases give the spelling of uasurferCrawlers to the names of the
// list of crawler-user-agents that denote the same crawler as one of them,
// by the name that the list gives. A name that differs from one of
// uasurferCrawlers only in case, spaces, - or _ is here; a different crawler
// of the same operator, such as GPTBot or Googlebot-Image, is not. A test
// fixes the table.
var crawlerAliases = map[string]string{
	"bingbot":             "Bing Bot",
	"msnbot":              "MSN Bot",
	"Slurp":               "Yahoo Slurp",
	"facebookexternalhit": "Facebook Crawler",
	"coccoc":              "Coccoc Bot",
	"Applebot":            "Apple Bot",
	"Baiduspider":         "Baidu Spider",
	"DuckDuckBot":         "DuckDuck Bot",
	"LinkedInBot":         "LinkedIn Bot",
	"Twitterbot":          "Twitter Bot",
	"PerplexityBot":       "Perplexity Bot",
	"yandex.com/bots":     "Yandex Bot",
}

// crawlerNames returns the name of each pattern of the list of
// crawler-user-agents, by its index in the list: the name that listName
// gives, in the spelling of crawlerAliases when it has one. It builds them
// once.
var crawlerNames = sync.OnceValue(func() []string {
	out := make([]string, len(agents.Crawlers))
	for i, c := range agents.Crawlers {
		out[i] = listName(c.Pattern)
		if alias, ok := crawlerAliases[out[i]]; ok {
			out[i] = alias
		}
	}
	return out
})

// Bots returns every name that a record can give to a bot, each once, with
// the description that the list of crawler-user-agents gives to it: the
// names of the list, in its order, with the description of the first of
// their patterns that has one, then the names of uasurferCrawlers that the
// list does not give, without a description, in the order of the names. A
// record has the description of the pattern that matched, and none when only
// uasurfer recognizes the bot. A bot without a name is not one of them.
func Bots() []Bot {
	var out []Bot
	index := map[string]int{}
	add := func(b Bot) {
		switch i, ok := index[b.Name]; {
		case b.Name == "":
		case !ok:
			index[b.Name] = len(out)
			out = append(out, b)
		case out[i].Description == "":
			out[i].Description = b.Description
		}
	}
	descriptions := crawlerDescriptions()
	for i, name := range crawlerNames() {
		add(Bot{Name: name, Description: descriptions[i]})
	}
	for _, name := range slices.Sorted(maps.Values(uasurferCrawlers)) {
		add(Bot{Name: name})
	}
	return out
}

// listName returns the name that the list gives to pattern: its name in
// crawlerPatternNames, or the text of a literal pattern, or empty for a
// pattern that is neither.
func listName(pattern string) string {
	if name, ok := crawlerPatternNames[pattern]; ok {
		return name
	}
	name, _ := literalName(pattern)
	return name
}

// literalName returns the name that a literal pattern gives: its text,
// without escapes, without ^ at its start and $ at its end, without the spaces
// around it and without a final slash, as Googlebot for Googlebot\/. It
// reports false for a pattern that is not a literal.
func literalName(pattern string) (string, bool) {
	re, err := syntax.Parse(pattern, syntax.Perl)
	if err != nil {
		return "", false
	}
	parts := []*syntax.Regexp{re}
	if re.Op == syntax.OpConcat {
		parts = re.Sub
	}
	if len(parts) > 0 && (parts[0].Op == syntax.OpBeginText || parts[0].Op == syntax.OpBeginLine) {
		parts = parts[1:]
	}
	if len(parts) > 0 && (parts[len(parts)-1].Op == syntax.OpEndText || parts[len(parts)-1].Op == syntax.OpEndLine) {
		parts = parts[:len(parts)-1]
	}
	if len(parts) != 1 || parts[0].Op != syntax.OpLiteral || parts[0].Flags&syntax.FoldCase != 0 {
		return "", false
	}
	name := strings.TrimSpace(string(parts[0].Rune))
	return strings.TrimSpace(strings.TrimSuffix(name, "/")), true
}
